CREATE TABLE IF NOT EXISTS gives (id INTEGER PRIMARY KEY AUTOINCREMENT, spot TEXT NOT NULL, created_at INTEGER NOT NULL, ends_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS idx_gives_spot_recent ON gives(spot,created_at DESC);
CREATE TABLE IF NOT EXISTS counters (day TEXT NOT NULL, metric TEXT NOT NULL, total INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(day,metric));
CREATE TABLE IF NOT EXISTS limits (ip_hash TEXT PRIMARY KEY, last_attempt INTEGER NOT NULL);
